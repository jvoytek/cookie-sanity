    ADD COLUMN IF NOT EXISTS "badges_earned" bigint[] DEFAULT '{}'::bigint[] NOT NULL;


ALTER TABLE "public"."sellers"
    ADD COLUMN IF NOT EXISTS "badges_received" bigint[] DEFAULT '{}'::bigint[] NOT NULL;


CREATE OR REPLACE FUNCTION public.remove_deleted_badge_from_sellers()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE public.sellers
    SET
        badges_earned = array_remove(badges_earned, OLD.id),
        badges_received = array_remove(badges_received, OLD.id)
    WHERE OLD.id = ANY(badges_earned) OR OLD.id = ANY(badges_received);

    RETURN OLD;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


DROP TRIGGER IF EXISTS remove_deleted_badge_from_sellers_trigger ON public.badges;


CREATE TRIGGER remove_deleted_badge_from_sellers_trigger
    AFTER DELETE ON public.badges
    FOR EACH ROW
    EXECUTE FUNCTION public.remove_deleted_badge_from_sellers();


CREATE POLICY "Allow owners/collaborators to view their own badges" ON public.badges FOR SELECT TO authenticated USING ( public.is_season_owner(season, (SELECT auth.uid())) OR public.is_season_collaborator(season, (SELECT auth.uid())) );
CREATE POLICY "Allow owners/collaborators to delete their own badges" ON public.badges FOR DELETE TO authenticated USING ( public.is_season_owner(season, (SELECT auth.uid())) OR public.is_season_collaborator(season, (SELECT auth.uid())) );
CREATE POLICY "Allow owners/collaborators to insert their own badges" ON public.badges FOR INSERT TO authenticated WITH CHECK ( public.is_season_owner(season, (SELECT auth.uid())) OR public.is_season_collaborator(season, (SELECT auth.uid())) );
CREATE POLICY "Allow owners/collaborators to update their own badges" ON public.badges FOR UPDATE TO authenticated USING ( public.is_season_owner(season, (SELECT auth.uid())) OR public.is_season_collaborator(season, (SELECT auth.uid())) );
