CREATE TABLE IF NOT EXISTS "public"."badges" (
    "id" bigint NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "profile" "uuid",
    "name" character varying NOT NULL,
    "url" text,
    "program_level" character varying NOT NULL,
    "season" bigint NOT NULL,
    CONSTRAINT "badges_program_level_check" CHECK (
        ("program_level")::text = ANY (
            ARRAY[
                'daisy'::character varying,
                'brownie'::character varying,
                'junior'::character varying,
                'cadette'::character varying,
                'senior'::character varying,
                'ambassador'::character varying
            ]::text[]
        )
    )
);


